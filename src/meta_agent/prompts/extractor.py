"""Системный prompt и список инструментов агента-извлекателя."""

from src.meta_agent.configs import get_collection_catalog

_EXTRACTOR_TOOLS = [
    "remaining_steps — вернуть текущую итерацию, лимит итераций и приблизительный остаток вызовов инструментов.",
    "collection_schema — получить статус коллекции, число точек, векторы и поля payload; вызывай перед поиском по новой коллекции.",
    "list_dtos — показать доступные DTO в контексте: имена, краткое описание, колонки, число строк и sample.",
    "sample_dto — получить небольшую выборку строк существующего DTO по dto_name.",
    "search — выполнить семантический поиск в Qdrant и зарегистрировать найденные точки как DTO.",
    "filter_points — найти точки по точному совпадению значения payload-поля и зарегистрировать результат как DTO.",
    "scroll_points — получить страницу точек Qdrant с выбором payload-полей и опциональным точным фильтром; результат регистрируется как DTO.",
    "retrieve_by_id — получить точки по списку UUID-идентификаторов и зарегистрировать результат как DTO.",
    "data_extraction_report — передать структурированный отчёт об извлечении и завершить шаг извлекателя.",
]

_EXTRACTOR_TOOLS_BLOCK = "\n".join(f"- {tool}" for tool in _EXTRACTOR_TOOLS)
_COLLECTION_CATALOG = get_collection_catalog()

