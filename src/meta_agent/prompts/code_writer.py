"""Системный prompt и список инструментов агента code_writer."""

_CODE_WRITER_TOOLS = [
    "remaining_steps — вернуть текущую итерацию, лимит итераций и приблизительный остаток вызовов инструментов.",
    "list_dtos — показать доступные DTO в контексте: имена, краткое описание, колонки, число строк и sample.",
    "sample_dto — получить небольшую выборку строк существующего DTO по dto_name.",
    "validate_code — проверить Python-код без выполнения: синтаксис, компиляцию и базовые статические предупреждения.",
    "execute_code — выполнить проверенный Python-код с доступом к dto, df и разрешённым библиотекам.",
    "code_execution_report — передать код, результаты валидации и выполнения, ключевые наблюдения и завершить шаг.",
]

_CODE_WRITER_TOOLS_BLOCK = "\n".join(f"- {tool}" for tool in _CODE_WRITER_TOOLS)
_CODE_WRITER_DTO_ENV_VAR = "DTO_DATA_JSON"

